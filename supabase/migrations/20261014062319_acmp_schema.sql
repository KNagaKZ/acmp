-- Server-side access only. Do not add acmp to the exposed Data API schemas.
CREATE SCHEMA IF NOT EXISTS acmp;
REVOKE ALL ON SCHEMA acmp FROM PUBLIC, anon, authenticated;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'acmp_app') THEN
    CREATE ROLE acmp_app NOLOGIN NOSUPERUSER NOBYPASSRLS;
  END IF;
END $$;

CREATE TABLE acmp.teachers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, surname text NOT NULL, email text NOT NULL,
  password_hash text NOT NULL,
  is_super_admin integer NOT NULL DEFAULT 0 CHECK (is_super_admin = 0),
  must_change_password integer NOT NULL DEFAULT 0 CHECK (must_change_password IN (0, 1)),
  one_time_password_hash text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX teachers_email_unique ON acmp.teachers (lower(email));

CREATE TABLE acmp.students (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES acmp.teachers(id) ON DELETE CASCADE,
  name text NOT NULL, surname text NOT NULL DEFAULT '', acmp_id text NOT NULL CHECK (acmp_id ~ '^[1-9][0-9]*$'),
  solved_count integer NOT NULL DEFAULT 0 CHECK (solved_count >= 0),
  unsolved_count integer NOT NULL DEFAULT 0 CHECK (unsolved_count >= 0),
  acmp_name text, last_synced timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (teacher_id, acmp_id)
);
CREATE TABLE acmp.student_rewards (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id integer NOT NULL REFERENCES acmp.students(id) ON DELETE CASCADE,
  target_solved integer NOT NULL CHECK (target_solved > 0), gift_name text NOT NULL,
  image_data text, delivered integer NOT NULL DEFAULT 0 CHECK (delivered IN (0, 1)),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE acmp.student_groups (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES acmp.teachers(id) ON DELETE CASCADE,
  name text NOT NULL, slug text NOT NULL UNIQUE,
  show_gifts integer NOT NULL DEFAULT 0 CHECK (show_gifts IN (0, 1)),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE acmp.group_students (
  group_id integer NOT NULL REFERENCES acmp.student_groups(id) ON DELETE CASCADE,
  student_id integer NOT NULL REFERENCES acmp.students(id) ON DELETE CASCADE,
  PRIMARY KEY (group_id, student_id)
);
CREATE TABLE acmp.ranklist_entries (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id integer NOT NULL REFERENCES acmp.teachers(id) ON DELETE CASCADE,
  region text NOT NULL CHECK (region IN ('south', 'north', 'east', 'west')),
  entry_type text NOT NULL CHECK (entry_type IN ('student', 'group')),
  student_id integer REFERENCES acmp.students(id) ON DELETE CASCADE,
  group_id integer REFERENCES acmp.student_groups(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((entry_type = 'student' AND student_id IS NOT NULL AND group_id IS NULL)
    OR (entry_type = 'group' AND group_id IS NOT NULL AND student_id IS NULL))
);
CREATE UNIQUE INDEX ranklist_student_unique ON acmp.ranklist_entries (region, student_id) WHERE student_id IS NOT NULL;
CREATE UNIQUE INDEX ranklist_group_unique ON acmp.ranklist_entries (region, group_id) WHERE group_id IS NOT NULL;
CREATE INDEX rewards_student_idx ON acmp.student_rewards(student_id);
CREATE INDEX groups_teacher_idx ON acmp.student_groups(teacher_id);
CREATE INDEX group_members_student_idx ON acmp.group_students(student_id);
CREATE INDEX ranklist_teacher_idx ON acmp.ranklist_entries(teacher_id);
CREATE INDEX ranklist_student_idx ON acmp.ranklist_entries(student_id);
CREATE INDEX ranklist_group_idx ON acmp.ranklist_entries(group_id);

GRANT USAGE ON SCHEMA acmp TO acmp_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA acmp TO acmp_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA acmp TO acmp_app;
REVOKE ALL ON ALL TABLES IN SCHEMA acmp FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA acmp FROM PUBLIC, anon, authenticated;

-- The restricted app role is used ONLY by our server, which authorizes teacher/admin requests.
DO $$ DECLARE table_name text; BEGIN
  FOREACH table_name IN ARRAY ARRAY['teachers','students','student_rewards','student_groups','group_students','ranklist_entries'] LOOP
    EXECUTE format('ALTER TABLE acmp.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('CREATE POLICY server_access ON acmp.%I TO acmp_app USING (true) WITH CHECK (true)', table_name);
  END LOOP;
END $$;
